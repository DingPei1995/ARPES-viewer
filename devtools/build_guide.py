"""Assemble the user guides from their parts.

The guide is written in small files, one per part, under
``docs/guide/<lang>/`` (``00_front.md``, ``01_...md`` ... ``08_...md``), so
that a change to one tool touches one short file. This script joins them
into the single ``docs/USER_GUIDE_<lang>.md`` that GitHub shows and
``build_guide_pdfs.py`` prints, with:

* the table of contents, made from the headings (``# Part ...`` and the
  numbered ``## N.M ...`` sections) -- so it never falls behind;
* the links written for a part's own folder (``../../images/x.png``,
  ``../../../CHANGELOG.md``) rewritten for ``docs/`` (``images/x.png``,
  ``../CHANGELOG.md``), so each part also reads correctly on its own.

In ``00_front.md`` the line ``<!-- contents -->`` marks where the table of
contents goes. Links between sections are anchors as GitHub makes them
(``#42-fermi-edge-fit`` for ``## 4.2 Fermi edge fit``).

``test/test_user_guide.py`` fails when a ``USER_GUIDE_<lang>.md`` is not
what the parts make, or when an anchor or an image in it does not exist.

Usage:  python devtools/build_guide.py [--check] [lang ...]   (default: all)
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCS = os.path.join(HERE, "docs")
PARTS = os.path.join(DOCS, "guide")
LANGS = ("en", "zh", "fr")
CONTENTS = {"en": "Contents", "zh": "目录", "fr": "Table des matières"}


def slug(heading: str) -> str:
    """The anchor GitHub (and pandoc's gfm reader) gives a heading."""
    text = re.sub(r"[`*_]", "", heading.strip().lower())
    text = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", text)
    text = "".join(c for c in text if c.isalnum() or c in " -_")
    return text.replace(" ", "-")


def parts(lang: str) -> list:
    folder = os.path.join(PARTS, lang)
    return [os.path.join(folder, name) for name in sorted(os.listdir(folder))
            if name.endswith(".md")]


def _relink(text: str) -> str:
    """Links written from docs/guide/<lang>/ made right for docs/."""
    return re.sub(r'(\]\(|src=")\.\./\.\./', r"\1", text)


def headings(text: str):
    """``(level, title)`` of the ``#`` and ``##`` headings outside code."""
    out, fenced = [], False
    for line in text.splitlines():
        if line.startswith("```"):
            fenced = not fenced
            continue
        if fenced:
            continue
        match = re.match(r"^(#{1,2}) (.+?)\s*$", line)
        if match:
            out.append((len(match.group(1)), match.group(2)))
    return out


def contents(lang: str, body: str) -> str:
    lines = [f"## {CONTENTS[lang]}", ""]
    for level, title in headings(body):
        if level == 1:
            lines += ["", f"**[{title}](#{slug(title)})**", ""]
        elif re.match(r"^\d+\.\d+ ", title):
            lines.append(f"- [{title}](#{slug(title)})")
    return "\n".join(lines).replace("\n\n\n", "\n\n").strip() + "\n"


def build(lang: str) -> str:
    files = parts(lang)
    front = _relink(open(files[0], encoding="utf-8").read())
    body = "\n\n---\n\n".join(
        _relink(open(path, encoding="utf-8").read()).strip() for path in files[1:])
    if "<!-- contents -->" not in front:
        raise ValueError(f"{files[0]} has no <!-- contents --> line")
    note = ("<!-- Generated by devtools/build_guide.py from docs/guide/"
            f"{lang}/: edit those files, not this one. -->\n")
    text = front.replace("<!-- contents -->", contents(lang, body).strip())
    return text.rstrip() + "\n\n---\n\n" + body.strip() + "\n\n" + note


def target(lang: str) -> str:
    return os.path.join(DOCS, f"USER_GUIDE_{lang}.md")


def main(argv) -> int:
    check = "--check" in argv
    langs = [a for a in argv if not a.startswith("--")] or list(LANGS)
    stale = []
    for lang in langs:
        text = build(lang)
        path = target(lang)
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
        if check:
            if old != text:
                stale.append(path)
            continue
        if old != text:
            with open(path, "w", encoding="utf-8", newline="\n") as handle:
                handle.write(text)
        print("wrote" if old != text else "unchanged", path)
    if stale:
        print("out of date (run python devtools/build_guide.py):", *stale)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
